const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const root = path.resolve(__dirname, '..');
process.chdir(root);
const temp = path.join(root, '.tmp');
fs.mkdirSync(temp, {recursive: true});
execFileSync(process.execPath, [require.resolve('tailwindcss/lib/cli.js'), '-i', 'src/styles.css', '-o', '.tmp/app.css', '--minify'], {stdio: 'pipe'});
const css = fs.readFileSync('.tmp/app.css', 'utf8');
const files = ['data.js', 'engine.js', 'persistence.js', 'accessibility.js', 'app.js'];
const js = files.map(file => fs.readFileSync(path.join('src', file), 'utf8')).join('\n');
new (require('node:vm').Script)(js);
const template = fs.readFileSync('src/index.html', 'utf8');
const license = fs.readFileSync(require.resolve('tailwindcss/LICENSE'), 'utf8');
const output = '<!-- GENERATED by npm run build. Edit src/ instead. -->\n<!-- Tailwind CSS license:\n' + license + '\n-->\n' + template
  .replace('/* @APP_CSS */', () => css)
  .replace('/* @APP_JS */', () => js.replace(/<\/script/gi, '<\\/script'));
for (const file of ['index.html', 'wall_street_1980_tycoon.html']) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8') !== output) throw new Error(file + ' is stale; run npm run build');
  } else fs.writeFileSync(file, output);
}
console.log(process.argv.includes('--check') ? 'Generated entrypoints are current.' : 'Built two offline entrypoints from src/.');
